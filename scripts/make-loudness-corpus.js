// make-loudness-corpus.js — SLICE 3 loudness corpus (docs/dsp-loudness-meter.md §5.2). Run from the repo root:
//
//   node scripts/make-loudness-corpus.js
//
// 1. THE KNOWN −23 LUFS FILE (ref_m23.wav). The corpus music (native/goldens/inputs/music.wav) is measured by
//    an INDEPENDENT meter — ffmpeg's `ebur128` filter (libavfilter's own implementation, not the `ebur128`
//    crate the engine links) — gained to −23.0 LUFS integrated, written as 24-bit PCM, and the WRITTEN file
//    is measured again. That second reading is the reference the engine's meter is held to (±0.1 LU).
// 2. THE EBU TEST SET (Jeff's ruling 7). If the EBU loudness test set v5 zip has been unpacked into
//    native/goldens/inputs/ebu/, every file is hashed so a test can refuse to run against different bytes.
//
// Everything lands in native/goldens/manifest-loudness.json (tracked). The WAVs stay gitignored, like every
// corpus input. ffmpeg is the copy the app already ships: node_modules/ffmpeg-static.
"use strict";
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const ROOT = path.join(__dirname, "..");
const INPUTS = path.join(ROOT, "native", "goldens", "inputs");
const MANIFEST = path.join(ROOT, "native", "goldens", "manifest-loudness.json");
const FFMPEG = require("ffmpeg-static");
const TARGET = -23.0;

// FNV-1a 64 over the bytes — the SAME identity offline_render.rs::fnv_bytes gives the corpus inputs, including
// its offset basis 1469598103934665603 (not the textbook 14695981039346656037): every golden and input hash in
// native/goldens was made with it, so this must match it, not the textbook.
function fnvBytes(buf) {
  let h = 1469598103934665603n;
  const p = 0x100000001b3n, m = 0xffffffffffffffffn;
  for (const b of buf) { h ^= BigInt(b); h = (h * p) & m; }
  return h.toString(16).padStart(16, "0");
}

// Integrated loudness by ffmpeg's ebur128 filter, full precision: the per-frame metadata carries the running
// integrated value (lavfi.r128.I) as a float; its last value is the programme's integrated loudness. (The
// filter's printed summary rounds to 0.1 LU, which is the tolerance itself — not good enough for a reference.
// The metadata is printed to 0.001 LU, so the reference is good to ±0.0005 LU.)
function ffmpegIntegrated(file) {
  const r = spawnSync(FFMPEG, ["-hide_banner", "-nostats", "-i", file,
    "-af", "ebur128=metadata=1,ametadata=mode=print:key=lavfi.r128.I:file=-", "-f", "null", "-"],
    { encoding: "utf8", maxBuffer: 1 << 30 });
  if (r.status !== 0) throw new Error(`ffmpeg failed on ${file}: ${r.stderr.slice(-800)}`);
  const vals = [...r.stdout.matchAll(/lavfi\.r128\.I=(-?[0-9.]+|-inf|nan)/g)].map(m => Number(m[1]));
  const last = vals.filter(Number.isFinite).pop();
  if (last === undefined) throw new Error(`no integrated value from ffmpeg for ${file}`);
  return last;
}

function ffmpegVersion() {
  const r = spawnSync(FFMPEG, ["-hide_banner", "-version"], { encoding: "utf8" });
  return (r.stdout.split("\n")[0] || "").trim();
}

function main() {
  const src = path.join(INPUTS, "music.wav");
  if (!fs.existsSync(src)) throw new Error(`corpus music missing at ${src} (see native/goldens/manifest.json)`);
  const out = path.join(INPUTS, "ref_m23.wav");

  const srcI = ffmpegIntegrated(src);
  let gain = TARGET - srcI;
  console.log(`music.wav: ffmpeg I = ${srcI.toFixed(3)} LUFS -> gain ${gain.toFixed(4)} dB`);
  let refI = NaN;
  // Two passes at most: the 24-bit write can move the reading by a few thousandths; correct it once.
  for (let pass = 1; pass <= 2; pass++) {
    const r = spawnSync(FFMPEG, ["-hide_banner", "-y", "-i", src, "-af", `volume=${gain.toFixed(6)}dB`,
      "-c:a", "pcm_s24le", out], { encoding: "utf8" });
    if (r.status !== 0) throw new Error(`ffmpeg write failed: ${r.stderr.slice(-800)}`);
    refI = ffmpegIntegrated(out);
    console.log(`pass ${pass}: ref_m23.wav ffmpeg I = ${refI.toFixed(3)} LUFS`);
    if (Math.abs(refI - TARGET) < 0.0015) break;
    gain += TARGET - refI;
  }

  const m = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, "utf8")) : {};
  m.about = "Slice 3 loudness corpus (docs/dsp-loudness-meter.md §5). Generated by scripts/make-loudness-corpus.js. "
          + "WAVs are gitignored; these hashes pin the bytes the loudness tests were run against.";
  m.reference = { tool: ffmpegVersion(), filter: "ebur128 (libavfilter), per-frame lavfi.r128.I, last value",
                  precision_lu: 0.001 };
  const bytes = fs.readFileSync(out);
  m.ref_m23 = { file: "ref_m23.wav", from: "music.wav", format: "pcm_s24le", bytes: bytes.length,
                fnv: fnvBytes(bytes), ffmpeg_i: Number(refI.toFixed(3)), target: TARGET };

  const ebuDir = path.join(INPUTS, "ebu");
  if (fs.existsSync(ebuDir)) {
    const files = fs.readdirSync(ebuDir).filter(f => /\.wav$/i.test(f)).sort();
    m.ebu = { set: "EBU loudness test set v5.0 (ebu-loudness-test-setv05.zip, tech.ebu.ch)", files: {} };
    for (const f of files) {
      const b = fs.readFileSync(path.join(ebuDir, f));
      m.ebu.files[f] = { bytes: b.length, fnv: fnvBytes(b) };
    }
    console.log(`EBU set: ${files.length} WAV files hashed`);
  } else {
    console.log(`EBU set: not present at ${ebuDir} (unzip ebu-loudness-test-setv05.zip there)`);
  }
  fs.writeFileSync(MANIFEST, JSON.stringify(m, null, 1) + "\n");
  console.log(`wrote ${path.relative(ROOT, MANIFEST)}`);
}

main();
