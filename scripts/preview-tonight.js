// scripts/preview-tonight.js — what Generate (the one pick, Phase 2) would put in a station's log for a day, on a COPY.
//
// Jeff, 2026-10-18: "In the 2:15 report, list tonight's HalloVeen 3–10 PM hours: every UNSCHEDULED slot and short fill,
// so I can fix my rules or set a fallback myself before 3 PM."
//
// Read-only on the source: the database is copied with VACUUM INTO from a read-only handle, the copy is migrated the way
// the app migrates on launch, the real Generate runs on the copy (electron/generate-core.js), the copy is deleted.
// It reports, per hour: the songs placed, every UNSCHEDULED slot with the rule that blocked the closest songs, and how
// much of the hour the log leaves empty before :00 (that time is filled on air from the hour's own clock, under the
// same rules, or stays silent if nothing passes).
//
//   node scripts/preview-tonight.js [--db <openair.db>] [--station 2] [--date 2026-10-18] [--from 15] [--to 22]
"use strict";
const fs = require("fs"), os = require("os"), path = require("path");
const { createRequire } = require("module");
const { DatabaseSync } = require("node:sqlite");
const argv = process.argv.slice(2);
const opt = (n, d) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : d; };
const ROOT = path.join(__dirname, "..");
const SID = Number(opt("--station", 2));
const FROM = Number(opt("--from", 15)), TO = Number(opt("--to", 22));
let SRC = opt("--db", null);
if (!SRC) {
  const prof = path.join(process.env.LOCALAPPDATA || "", "Ether", "profiles");
  for (const d of fs.readdirSync(prof)) { if (d.includes(".retired") || d.startsWith("_")) continue; const f = path.join(prof, d, "openair.db"); if (fs.existsSync(f)) { SRC = f; break; } }
}
const day = (() => { const s = opt("--date", null); const d = s ? new Date(s + "T00:00:00") : new Date(); d.setHours(0, 0, 0, 0); return d; })();
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), "ether-preview-"));
const COPY = path.join(TMP, "preview.db");
{ const ro = new DatabaseSync(SRC, { readOnly: true }); try { ro.exec(`VACUUM INTO '${COPY.replace(/'/g, "''")}'`); } finally { ro.close(); } }
const raw = new DatabaseSync(COPY);
const db = { prepare: (q) => raw.prepare(q), exec: (q) => raw.exec(q), transaction: (fn) => (...a) => { raw.exec("SAVEPOINT p"); try { const r = fn(...a); raw.exec("RELEASE p"); return r; } catch (e) { raw.exec("ROLLBACK TO p"); raw.exec("RELEASE p"); throw e; } } };
// migrate the copy as the app does on launch (main.js runMigrationChain, lifted by name)
const MAIN = fs.readFileSync(path.join(ROOT, "electron", "main.js"), "utf8");
const st = MAIN.indexOf("\nfunction runMigrationChain("); const m = /\r?\n\}\r?\n/.exec(MAIN.slice(st + 1));
new Function("path", "__dirname", "require", "console", MAIN.slice(st + 1, st + 1 + m.index + m[0].length) + "\nreturn runMigrationChain;")(path, path.join(ROOT, "electron"), createRequire(path.join(ROOT, "electron", "main.js")), { log() {}, error() {}, warn() {} })(db);

(async () => {
  const gen = require(path.join(ROOT, "electron", "generate-core.js"));
  const ctx = gen.buildScheduleCtx(db, SID);
  const dayStart = Math.floor(day.getTime() / 1000);
  const from = Math.max(dayStart + FROM * 3600, Math.ceil(Date.now() / 1000 / 3600) * 3600 > dayStart + FROM * 3600 && day.toDateString() === new Date().toDateString() ? dayStart + FROM * 3600 : dayStart + FROM * 3600);
  ctx.planWindow(from, dayStart + TO * 3600);
  gen.resetGenSlice();
  for (let h = FROM; h < TO; h++) await gen.generateDayRows(day, ctx, from, h);
  const st0 = raw.prepare("SELECT name FROM stations WHERE id=?").get(SID);
  const rules = ctx.rules;
  console.log(`${st0 ? st0.name : "station " + SID} — ${day.toDateString()} ${FROM}:00–${TO}:00, generated by the one pick on a copy of ${SRC}`);
  console.log(`rules (Programming preferences): song ${rules.songMin ?? "off"} · artist ${rules.artistMin ?? "off"} · title ${rules.titleMin ?? "off"} min · fallback category: ${ctx.fallbackCat ?? "none set"}`);
  let totalU = 0;
  for (let h = FROM; h < TO; h++) {
    const hs = dayStart + h * 3600, he = hs + 3600;
    const rows = ctx.generatedRows.filter(r => r.scheduled_at >= hs && r.scheduled_at < he);
    const songs = rows.filter(r => r.song_id != null && r.content_class !== "UNSCHEDULED");
    const un = rows.filter(r => r.content_class === "UNSCHEDULED");
    const spots = rows.filter(r => r.content_class === "SPOT");
    const audible = rows.filter(r => r.content_class !== "UNSCHEDULED");
    const end = audible.length ? Math.max(...audible.map(r => r.scheduled_at + (r.duration_s || 0))) : hs;
    const unSec = un.reduce((n, r) => n + (r.duration_s || 0), 0);
    const empty = Math.max(0, he - end) + unSec;
    totalU += un.length;
    const label = new Date(hs * 1000).toLocaleTimeString([], { hour: "numeric" });
    console.log(`\n${label}: ${songs.length} songs, ${spots.length} spots, ${un.length} UNSCHEDULED` + (empty > 0 ? ` · ${Math.round(empty / 60)} min of the hour has no planned song (filled on air from the hour's clock under the rules, or silent if nothing passes)` : ""));
    for (const u of un) {
      let pr = {}; try { pr = JSON.parse(u.pick_reason || "{}"); } catch {}
      const why = (pr.closest || []).map(c => `${c.title} — ${c.rule} ${c.measuredMin} of ${c.settingMin} min`).join("; ") || "the category has no song for this hour";
      console.log(`   UNSCHEDULED ${new Date(u.scheduled_at * 1000).toLocaleTimeString([], { hour: "numeric", minute: "2-digit" })}  ${u.title.split(" (")[0].replace("UNSCHEDULED — ", "")}: ${why}`);
    }
  }
  console.log(`\ntotal UNSCHEDULED ${FROM}:00–${TO}:00: ${totalU}`);
  raw.close(); try { fs.rmSync(TMP, { recursive: true, force: true }); } catch {}
})().catch(e => { console.error("PREVIEW ERROR:", e && e.stack || e); try { raw.close(); fs.rmSync(TMP, { recursive: true, force: true }); } catch {} process.exit(2); });
